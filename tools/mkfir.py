"""Write the resampling filter of the kernel's sound output (emu68/src/psmac/psmac_audio_fir.h).

    tools/mkfir.py > emu68/src/psmac/psmac_audio_fir.h

The kernel turns the Macintosh's 22,257 Hz (the ASC) and 44,100 Hz (the sound card) into the
output's 48,000 or 44,100 Hz on core 1 (psmac_audio.c). Both are upsampling, or nearly so, so one
low-pass filter serves both: a windowed sinc whose cutoff is 0.45 of the input rate, in TAPS
input samples, sampled at PHASES fractional positions between two input samples. The window is
Blackman-Harris (four terms), which puts the first side lobe about 92 dB down: far below what an
8-bit ASC sample can resolve, and below a 16-bit sample's quantisation for the card. Each phase
is scaled so that its coefficients sum to exactly 32768, so DC and quiet passages come out with
unity gain whatever the phase. Written by hand on 20 November 2026; the kernel takes the
numbers as they are and computes nothing at run time (the kernel has no floating point:
Emu68 keeps the FP registers for the 68k's JIT).
"""
import math, sys

TAPS, PHASES, CUTOFF = 32, 128, 0.45


def window(t):
    """Blackman-Harris over t in [-TAPS/2, TAPS/2]."""
    x = (t + TAPS / 2) / TAPS
    if x < 0 or x > 1:
        return 0.0
    a0, a1, a2, a3 = 0.35875, 0.48829, 0.14128, 0.01168
    return a0 - a1 * math.cos(2 * math.pi * x) + a2 * math.cos(4 * math.pi * x) - a3 * math.cos(6 * math.pi * x)


def sinc(x):
    return 1.0 if x == 0 else math.sin(math.pi * x) / (math.pi * x)


rows = []
for p in range(PHASES):
    f = p / PHASES
    # tap k multiplies the input sample k (0 the oldest of TAPS); the output lies f of a sample
    # after sample TAPS/2 - 1 (psmac_audio.c, rs_out)
    h = [2 * CUTOFF * sinc(2 * CUTOFF * (k - TAPS / 2 + 1 - f)) * window(k - TAPS / 2 + 1 - f) for k in range(TAPS)]
    s = sum(h)
    q = [round(v * 32768 / s) for v in h]
    q[TAPS // 2 - 1 if f < 0.5 else TAPS // 2] += 32768 - sum(q)   # the rounding's remainder on the largest tap
    assert all(-32768 <= v <= 32767 for v in q)
    rows.append(q)

out = sys.stdout
out.write("/* SPDX-License-Identifier: MPL-2.0\n *\n * psmac_audio_fir.h - generated by tools/mkfir.py: do not edit.\n"
          f" * The sound output's resampling filter: {PHASES} phases of {TAPS} taps, Q15, a windowed sinc\n"
          f" * (Blackman-Harris) cut off at {CUTOFF} of the input rate; each phase sums to 32768.\n */\n")
out.write(f"#define FIR_TAPS {TAPS}\n#define FIR_PHASES {PHASES}\n#define FIR_PHASE_SHIFT {32 - int(math.log2(PHASES))}\n")
out.write(f"static const int16_t fir[FIR_PHASES][FIR_TAPS] = {{\n")
for q in rows:
    out.write("    { " + ", ".join(str(v) for v in q) + " },\n")
out.write("};\n")
