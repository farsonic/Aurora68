"""mkpcfont.py - the PC card's 6 x 13 and 6 x 12 text fonts for the Mac's one-bit screen, as a C header for the kernel.

    curl -LO https://gitlab.freedesktop.org/xorg/font/misc-misc/-/raw/master/6x13.bdf
    curl -LO https://gitlab.freedesktop.org/xorg/font/misc-misc/-/raw/master/6x12.bdf
    python3 tools/mkpcfont.py 6x13.bdf 6x12.bdf -o emu68/src/psmac/psmac_pc_font.h

Backstory (23 November 2026, docs/19-pc-card.md). The PC card draws the PC's text screen (the firmware, DOS, a
Linux console) into a window on the Mac from its cells, never from pixels. On HDMI it can use the PC's own 8 x 16
font, but the Macintosh SE's screen is 512 x 342: 80 x 25 cells of 8 x 16 would be 640 x 400, which does not fit.
At 6 x 13 they are 480 x 325, which fits the screen with a window's frame and title (the owner: "text mode
always fits"). The glyphs are the X Window System's "fixed" 6x13 (misc-fixed, the ISO 10646 version by Markus
Kuhn), which is in the public domain ("Public domain font. Share and enjoy.", the font's COPYRIGHT property and
the misc-misc package's COPYING); this tool picks out the 256 characters of the PC's code page 437, box drawing
and the graphic characters 1-31 and 127 included, and writes them one byte a row, the 6 pixels in bits 7-2.
A character the font lacks (none of the 256, as checked when this was written) becomes the font's default glyph.

The 6 x 12 ("Public domain terminal emulator font. Share and enjoy.") came the same day, from arithmetic: 80 x 25 cells
of 6 x 13 are 325 lines, and the SE's screen has 342, less the menu bar (20) and a document window's title bar and
frame (21): 301 lines for the window's content. So on a screen that short the card draws 6 x 12 cells, 480 x 300,
and 80 x 25 fits with the window's frame, as the owner asked ("text mode always fits"); 6 x 13 wherever it fits.
Standard library only, like every tool here.
"""
import argparse, sys

# code page 437's graphic characters for the control codes 1-31 and 127 (the PC's ROM font draws them; Python's
# cp437 codec maps those bytes to the control characters themselves)
LOW = [0x0000, 0x263A, 0x263B, 0x2665, 0x2666, 0x2663, 0x2660, 0x2022, 0x25D8, 0x25CB, 0x25D9, 0x2642, 0x2640,
       0x266A, 0x266B, 0x263C, 0x25BA, 0x25C4, 0x2195, 0x203C, 0x00B6, 0x00A7, 0x25AC, 0x21A8, 0x2191, 0x2193,
       0x2192, 0x2190, 0x221F, 0x2194, 0x25B2, 0x25BC]

def cp437(i):
    if i < 32: return LOW[i]
    if i == 127: return 0x2302
    return ord(bytes([i]).decode('cp437'))

def load(path):
    glyphs, enc, rows, bbx, inbm = {}, None, [], None, False
    default = 0
    for line in open(path, encoding='latin-1'):
        w = line.split()
        if not w: continue
        if w[0] == 'DEFAULT_CHAR': default = int(w[1])
        elif w[0] == 'ENCODING': enc = int(w[1])
        elif w[0] == 'BBX': bbx = [int(x) for x in w[1:5]]
        elif w[0] == 'BITMAP': inbm, rows = True, []
        elif w[0] == 'ENDCHAR':
            inbm = False
            if enc is not None and bbx: glyphs[enc] = (bbx, rows)
            enc, bbx = None, None
        elif inbm: rows.append(int(w[0], 16))
    return glyphs, default

def cell(g, h, ascent):
    """h rows of 6 pixels (bits 7-2) from a BDF glyph placed in the font's 6 x h box (ascent above the baseline)"""
    (bw, bh, bx, by), rows = g
    out = [0] * h
    nbytes = (bw + 7) // 8
    for r, bits in enumerate(rows):
        y = ascent - (by + bh) + r              # from the cell's top: the box's top is ascent above the baseline
        if not 0 <= y < h: continue
        v = bits << (8 * (1 - nbytes)) if nbytes < 2 else bits >> 8 * (nbytes - 1)   # the row's first byte
        v = (v >> bx) if bx >= 0 else (v << -bx)
        out[y] |= v & 0xFC
    return out

ap = argparse.ArgumentParser()
ap.add_argument('bdf13')
ap.add_argument('bdf12')
ap.add_argument('-o', required=True)
a = ap.parse_args()

def table(path, h, ascent):
    glyphs, default = load(path)
    missing, rows = [], []
    for i in range(256):
        g = glyphs.get(cp437(i))
        if g is None:
            missing.append(i); g = glyphs[default]
        rows.append(cell(g, h, ascent) if i else [0] * h)
    return rows, missing

with open(a.o, 'w') as f:
    f.write('/* psmac_pc_font.h - generated by tools/mkpcfont.py from the X Window System\'s misc-fixed 6x13 and 6x12 (ISO 10646-1):\n'
            '   the PC\'s code page 437 in 6 x 13 and 6 x 12 cells, one byte a row, the six pixels in bits 7-2, for the PC card\'s\n'
            '   text on the Mac\'s one-bit screen (psmac_pc.c, docs/19-pc-card.md). The glyphs are in the public domain: "Public\n'
            '   domain font.  Share and enjoy." and "Public domain terminal emulator font.  Share and enjoy." (the fonts\'\n'
            '   COPYRIGHT properties; the misc-misc package\'s COPYING). This file: MPL-2.0. Do not edit; run the tool again. */\n')
    for name, path, h, asc in (('psmac_pc_font6x13', a.bdf13, 13, 11), ('psmac_pc_font6x12', a.bdf12, 12, 10)):
        rows, missing = table(path, h, asc)
        f.write(f'static const uint8_t {name}[256][{h}] = {{\n')
        for i, r in enumerate(rows):
            f.write('    { ' + ', '.join(f'0x{b:02x}' for b in r) + ' },' + f'   /* {i:02X} */\n')
        f.write('};\n')
        print(f"{name}: 256 glyphs of 6 x {h}" + (f"; not in the font (the default glyph instead): {missing}" if missing else ", all in the font"))
