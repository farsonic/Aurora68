"""mka2declrom.py - the Apple II card's declaration ROM, as a C header for the kernel (docs/20-apple-ii-card.md).

    python3 tools/mac/mka2declrom.py --drvr mac/build/a68apple.bin.raw -o emu68/src/psmac/psmac_a2_declrom.h
    (make -C mac a2-declrom)

The Aurora68 Apple II Card (23 November 2026; Aurora65's docs/DESIGN.md, "Which slot: $E") is the fourth NuBus card
that exists only in the Pi, made as the PC card's (tools/mac/mkpcdeclrom.py): its ROM is compiled into the kernel (a
kernel built with -DPSMAC_A2=ON serves it at the top of slot $E), and it carries the card's driver, ".A68A2"
(mac/a68apple.s), which the Slot Manager installs and opens at start-up.

sResources:
    1    board: type {catBoard 1, 0, 0, 0}, name "Aurora68 Apple II Card", BoardId (32) $4132 'A2', VendorInfo (vendor
         "Aurora68 project", revision "1", part "A68-A2")
    0x80 the Apple: type {$7050 'pP' (the project's vendor category; the PC card's is type 4), 5, drSwApple 1,
         drHw $4132 'A2'}, name "Aurora68_AppleII", sRsrcDrvrDir with ".A68A2" for sMacOS68020, sRsrcHWDevId 1,
         MinorBaseOS 0 and MinorLength $100000: the window (psmac_a2.h), at $FE000000 in 32-bit mode and $E00000
         in 24-bit mode ($FEE00000, the same memory: psmac_mmu.c)
"""
import argparse, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from declrom import DeclROM

ap = argparse.ArgumentParser()
ap.add_argument('-o', required=True)
ap.add_argument('--drvr', required=True, help="the card's driver, mac/a68apple.s assembled (build/a68apple.bin.raw)")
a = ap.parse_args()
drvr = open(a.drvr, 'rb').read()
assert drvr[19:19 + drvr[18]] == b'.A68A2', "the driver's name"

rom = DeclROM(byte_lanes=0x0F)
board = rom.sresource(1)
board.type(1, 0, 0, 0)
board.name('Aurora68 Apple II Card')
board.word(32, 0x4132)                          # BoardId 'A2'
vendor = type(board)(0)
vendor.cstring(1, 'Aurora68 project')           # VendorId
vendor.cstring(3, '1')                          # RevLevel
vendor.cstring(4, 'A68-A2')                     # PartNum
board.sublist(36, vendor)

a2 = rom.sresource(0x80)
a2.type(0x7050, 5, 1, 0x4132)
a2.name('Aurora68_AppleII')
drv = type(a2)(0); drv.longblock(2, drvr)       # sRsrcDrvrDir: sMacOS68020
a2.sublist(4, drv)                              # no sRsrcFlags: fOpenAtStart
a2.word(8, 1)                                   # sRsrcHWDevId
a2.long(10, 0x000000)                           # MinorBaseOS: the window at the start of the slot's space
a2.long(11, 0x100000)                           # MinorLength: A68A_WIN_SIZE

img = rom.build()
if len(img) > 0x4000:
    sys.exit(f"mka2declrom: {len(img)} bytes, the kernel has 16 KiB for it (PSMB_A2_ROM_SIZE)")
rows = [', '.join(f'0x{b:02x}' for b in img[i:i + 16]) for i in range(0, len(img), 16)]
with open(a.o, 'w') as f:
    f.write('/* psmac_a2_declrom.h - generated by tools/mac/mka2declrom.py (make -C mac a2-declrom): the Apple II card\'s\n'
            '   declaration ROM, served at the top of slot $E (psmac_a2.c). Do not edit. MPL-2.0. */\n')
    f.write(f'static const uint8_t psmac_a2_declrom[{len(img)}] = {{\n    ' + ',\n    '.join(rows) + '\n};\n')
print(f"{a.o}: the Apple II card's declaration ROM, {len(img)} bytes, its driver {len(drvr)}")
