"""mkauxnetdeclrom.py - the A/UX network card's declaration ROM, as a C header for the kernel (docs/24-aux-network.md).

    python3 tools/mac/mkauxnetdeclrom.py -o emu68/src/psmac/psmac_etalk_declrom.h

Backstory (27 November 2026). A/UX does not use Mac OS slot drivers: its own Ethernet driver for NuBus cards, ae6, is
linked into the kernel by autoconfig when a card with board ID 8 sits in a slot (/etc/master.d/ae6: "id 8"), and it
asks the ROM's Slot Manager for three things only: the board ID, a functional sResource of category Network (4), type
Ethernet (1), whatever its driver fields, and in that sResource an entry with ID $80 that leads to the six bytes of the
card's Ethernet address. The card this ROM describes is the Pi's (psmac_etalk.c): a DP8390 register file and 64 KiB of
buffer memory where ae6 expects them. The ROM is the project's own, written from those three facts; it carries no
driver, because A/UX has its own and Mac OS is not meant to use the card.

The address is not in the image. The entry $80 points eight bytes below the image's first byte, outside the length the
format block gives and so outside its checksum: the kernel writes the address of the Pi's network board there when it
knows it (the WiFi chip gives its address seconds after the Mac has started), and the checksum the Slot Manager took at
start-up stays true. A NuBus Ethernet card of 1987 had the same arrangement for the same reason: one ROM image for
every card, the address beside it.

sResources:
    1    board: type {catBoard 1, 0, 0, 0}, name "Aurora68 Ethernet for A/UX", BoardId (32) 8, VendorInfo (vendor
         "Aurora68 project", revision "1", part "A68-AUXNET")
    0x80 the Ethernet: type {catNetwork 4, typeEtherNet 1, drSw 1, drHw $4138 'A8'}, name
         "Network_Ethernet_Aurora68_AUX", MinorBaseOS $D0000 (the buffer memory, from the start of the slot's space),
         and $80: the Ethernet address, below the image
"""
import argparse, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from declrom import DeclROM

MAC_BELOW = 8           # the address cell: six bytes and two of padding, just below the image

ap = argparse.ArgumentParser()
ap.add_argument('-o', required=True)
a = ap.parse_args()

rom = DeclROM(byte_lanes=0x0F)
board = rom.sresource(1)
board.type(1, 0, 0, 0)
board.name('Aurora68 Ethernet for A/UX')
board.word(32, 8)                               # BoardId: the one A/UX's /etc/master.d/ae6 names
vendor = type(board)(0)
vendor.cstring(1, 'Aurora68 project')           # VendorId
vendor.cstring(3, '1')                          # RevLevel
vendor.cstring(4, 'A68-AUXNET')                 # PartNum
board.sublist(36, vendor)

net = rom.sresource(0x80)
net.type(4, 1, 1, 0x4138)                       # catNetwork, typeEtherNet; ae6 asks with the driver fields masked out
net.name('Network_Ethernet_Aurora68_AUX')
net.long(10, 0x0D0000)                          # MinorBaseOS: the buffer memory
net.below(0x80, MAC_BELOW)                      # the Ethernet address: SFindStruct, then SReadStruct of six bytes

img = rom.build()
if len(img) + MAC_BELOW > 0x1000:
    sys.exit(f"mkauxnetdeclrom: {len(img)} bytes, the kernel has one page for it and the address (psmac_etalk.c)")
rows = [', '.join(f'0x{b:02x}' for b in img[i:i + 16]) for i in range(0, len(img), 16)]
with open(a.o, 'w') as f:
    f.write('/* psmac_etalk_declrom.h - generated by tools/mac/mkauxnetdeclrom.py: the A/UX network card\'s declaration ROM,\n'
            '   served at the top of its slot (psmac_etalk.c). Do not edit. MPL-2.0. */\n')
    f.write(f'#define PSMAC_ETALK_MAC_BELOW {MAC_BELOW}u      /* the Ethernet address: this many bytes below the image\'s first byte */\n')
    f.write(f'static const uint8_t psmac_etalk_declrom[{len(img)}] = {{\n    ' + ',\n    '.join(rows) + '\n};\n')
print(f"{a.o}: the A/UX network card's declaration ROM, {len(img)} bytes")
