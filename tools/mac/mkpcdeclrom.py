"""mkpcdeclrom.py - the PC card's declaration ROM, as a C header for the kernel (docs/19-pc-card.md).

    python3 tools/mac/mkpcdeclrom.py --drvr mac/build/a68pc.bin.raw -o emu68/src/psmac/psmac_pc_declrom.h
    (make -C mac pc-declrom)

The Aurora68 PC Card (23 November 2026; Aurora86's docs/DESIGN.md, "The card in Aurora68") is the third NuBus
card that exists only in the Pi, after slot 9's and the video decoder in slot $C, made the same way: its ROM is
compiled into the kernel (a kernel built with -DPSMAC_PC=ON serves it at the top of slot $D), and it carries the
card's driver, ".A68PC" (mac/a68pc.s), which the Slot Manager installs and opens at start-up.

sResources:
    1    board: type {catBoard 1, 0, 0, 0}, name "Aurora68 PC Card", BoardId (32) $5043 'PC', VendorInfo (vendor
         "Aurora68 project", revision "1", part "A68-PC")
    0x80 the PC: type {$7050 'pP' (the project's vendor category, as the video decoder's type 3), 4, drSwApple 1,
         drHw $5043 'PC'}, name "Aurora68_PC", sRsrcDrvrDir with ".A68PC" for sMacOS68020, sRsrcHWDevId 1,
         MinorBaseOS 0 and MinorLength $100000: the window (psmac_pc.h), at $FD000000 in 32-bit mode and $D00000
         in 24-bit mode ($FDD00000, the same memory: psmac_mmu.c)
"""
import argparse, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from declrom import DeclROM

ap = argparse.ArgumentParser()
ap.add_argument('-o', required=True)
ap.add_argument('--drvr', required=True, help="the card's driver, mac/a68pc.s assembled (build/a68pc.bin.raw)")
a = ap.parse_args()
drvr = open(a.drvr, 'rb').read()
assert drvr[19:19 + drvr[18]] == b'.A68PC', "the driver's name"

rom = DeclROM(byte_lanes=0x0F)
board = rom.sresource(1)
board.type(1, 0, 0, 0)
board.name('Aurora68 PC Card')
board.word(32, 0x5043)                          # BoardId 'PC'
vendor = type(board)(0)
vendor.cstring(1, 'Aurora68 project')           # VendorId
vendor.cstring(3, '1')                          # RevLevel
vendor.cstring(4, 'A68-PC')                     # PartNum
board.sublist(36, vendor)

pc = rom.sresource(0x80)
pc.type(0x7050, 4, 1, 0x5043)
pc.name('Aurora68_PC')
drv = type(pc)(0); drv.longblock(2, drvr)       # sRsrcDrvrDir: sMacOS68020
pc.sublist(4, drv)                              # no sRsrcFlags: fOpenAtStart
pc.word(8, 1)                                   # sRsrcHWDevId
pc.long(10, 0x000000)                           # MinorBaseOS: the window at the start of the slot's space
pc.long(11, 0x100000)                           # MinorLength: A68P_WIN_SIZE

img = rom.build()
if len(img) > 0x4000:
    sys.exit(f"mkpcdeclrom: {len(img)} bytes, the kernel has 16 KiB for it (PSMB_PC_ROM_SIZE)")
rows = [', '.join(f'0x{b:02x}' for b in img[i:i + 16]) for i in range(0, len(img), 16)]
with open(a.o, 'w') as f:
    f.write('/* psmac_pc_declrom.h - generated by tools/mac/mkpcdeclrom.py (make -C mac pc-declrom): the PC card\'s\n'
            '   declaration ROM, served at the top of slot $D (psmac_pc.c). Do not edit. MPL-2.0. */\n')
    f.write(f'static const uint8_t psmac_pc_declrom[{len(img)}] = {{\n    ' + ',\n    '.join(rows) + '\n};\n')
print(f"{a.o}: the PC card's declaration ROM, {len(img)} bytes, its driver {len(drvr)}")
