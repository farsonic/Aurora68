#!/usr/bin/env python3
"""Turn a list of Toolbox calls (mac/c/traps.txt) into C-callable glue for the m68k ELF GCC.

    mktraps.py traps.txt -s toolbox_glue.s -H toolbox_gen.h

Each C function takes its arguments the GCC way (each in a 4-byte stack slot, the value in its
low end) and makes the Pascal call: room for the result, the arguments pushed left to right (an
INTEGER or CHAR as a word, a BOOLEAN as a byte in the high half of a word), the trap word; the
trap pops the arguments and leaves the result. The glue keeps D2 (GCC expects it kept, Pascal
code may change it) and returns the result in D0 (a long or pointer in A0 too: GCC's m68k
SVR4 ABI reads a pointer result from A0): a BOOLEAN as 0 or 1, an INTEGER sign-extended.

A trap that dispatches on a selector in D0 (the Movie Toolbox's _QuickTimeDispatch, the Alias and Folder
Managers' _AliasDispatch, the File Manager's _HighLevelFSDispatch) is written TRAP/SELECTOR, e.g.
AAAA/0188: the glue loads the selector into D0 (all of it, as moveq would) just before the trap. Result kind p is a pointer
(as l, typed void * in the header). Both added on 23 November 2026 for the QuickTime import (mac/vdec).
MPL-2.0.
"""
import argparse, re

ap = argparse.ArgumentParser()
ap.add_argument('spec'); ap.add_argument('-s', required=True); ap.add_argument('-H', required=True)
a = ap.parse_args()
asm = ['| generated by tools/mac/mktraps.py from mac/c/traps.txt: do not edit', '\t.text']
hdr = ['/* generated by tools/mac/mktraps.py from mac/c/traps.txt: do not edit */',
       '#ifndef TOOLBOX_GEN_H', '#define TOOLBOX_GEN_H']
ctype = {'-': 'void', 'l': 'long', 'w': 'short', 'b': 'int', 'c': 'int'}
for ln in open(a.spec):
    ln = ln.strip()
    if not ln or ln.startswith('#'):
        continue
    m = re.match(r'([0-9A-Fa-f]{4})(?:/([0-9A-Fa-f]{1,4}))?\s+([-lwbp])\s+(\w+)\((.*)\)$', ln)
    if not m:
        raise SystemExit(f"bad line: {ln}")
    trap, sel, res, name, args = m.groups()
    ptr = res == 'p'
    if ptr:
        res = 'l'
    params = []
    if args.strip():
        for p in args.split(','):
            decl, kind = p.rsplit(':', 1)
            params.append((decl.strip(), kind.strip()))
    rt = ctype[res]
    if res == 'l' and (ptr or name in ('NewWindow', 'FrontWindow', 'NewMenu', 'NewControl', 'TENew', 'GetResource')):
        rt = 'void *'
    hdr.append(f"{rt} {name}({', '.join(d for d, _ in params) or 'void'});")
    asm += [f'\t.globl\t{name}', f'{name}:', '\tlink\t%a6,#0', '\tmove.l\t%d2,-(%sp)']
    if res in 'l':
        asm.append('\tclr.l\t-(%sp)')
    elif res in 'wb':
        asm.append('\tclr.w\t-(%sp)')
    for i, (_, k) in enumerate(params):
        off = 8 + 4 * i
        if k == 'l':
            asm.append(f'\tmove.l\t{off}(%a6),-(%sp)')
        elif k in 'wc':
            asm.append(f'\tmove.w\t{off + 2}(%a6),-(%sp)')
        elif k == 'b':
            asm.append(f'\tmove.b\t{off + 3}(%a6),-(%sp)')
        else:
            raise SystemExit(f"{name}: kind {k}")
    if sel is not None:
        asm.append(f'\tmove.l\t#0x{sel.upper()},%d0')         # moveq's D0, or 303C's word: both read alike
    asm.append(f'\t.short\t0x{trap.upper()}')
    if res == 'l':
        asm += ['\tmove.l\t(%sp)+,%d0', '\tmove.l\t%d0,%a0']       # GCC's m68k SVR4 ABI: pointers come back in A0
    elif res == 'w':
        asm += ['\tmove.w\t(%sp)+,%d0', '\text.l\t%d0']
    elif res == 'b':
        asm += ['\tmoveq\t#0,%d0', '\ttst.b\t(%sp)+', '\tsne\t%d0', '\tneg.b\t%d0']
    asm += ['\tmove.l\t-4(%a6),%d2', '\tunlk\t%a6', '\trts']
hdr.append('#endif')
open(a.s, 'w').write('\n'.join(asm) + '\n')
open(a.H, 'w').write('\n'.join(hdr) + '\n')
