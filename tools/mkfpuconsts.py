"""mkfpuconsts.py - the constants of the exact FPU (emu68/src/psmac/psmac_fpu_consts.h).

22 November 2026 (issue #27, docs/17-exact-fpu.md). The exact FPU does the 68881's arithmetic with
Berkeley SoftFloat and its transcendental functions in 128-bit binary floating point. Both need
constants to more bits than any C compiler's long double carries, and the kernel has no floating
point of its own (core 0's FPU registers belong to the 68k), so they are computed here, with Python's
integers alone, and written as bit patterns:

  - FMOVECR's ROM: pi, log10(2), e, log2(e), log10(e), 0, ln 2, ln 10 and the powers 10^(2^n),
    each as 128 bits (a 64-bit significand and the 64 bits after it, the last made sticky when
    anything nonzero follows), so that the kernel can round them to any FPCR precision and mode
    and say whether the result is inexact, as the 68881 does;
  - 128-bit (quadruple) constants for the elementary functions: pi/2, ln 2 split in two
    (Cody and Waite's way, the high part short enough that n * ln2_hi is exact for |n| < 2^15),
    log2(e), log2(10), log10(e), 1/ln 2;
  - 2/pi to 16,700 bits, for the Payne and Hanek reduction of FSIN, FCOS, FTAN and FSINCOS
    arguments up to the largest extended number (2^16383 and a bit).

    python3 tools/mkfpuconsts.py > emu68/src/psmac/psmac_fpu_consts.h

Standard library only. The output is checked in; rerunning this gives the same file.
"""
import sys

P = 17600                    # fixed-point bits for everything (pi is needed to more than 2/pi's 16,700)


def isqrt(n):
    x = 1 << ((n.bit_length() + 1) // 2)
    while True:
        y = (x + n // x) // 2
        if y >= x:
            return x
        x = y


def atan_inv(k):
    """atan(1/k) * 2^P"""
    one = 1 << (P + 32)
    t = one // k
    s = t
    k2 = k * k
    n = 1
    while t:
        t //= k2
        n += 2
        s += -(t // n) if (n // 2) % 2 else t // n
    return s >> 32


def atanh_inv(k):
    """atanh(1/k) * 2^P"""
    one = 1 << (P + 32)
    t = one // k
    s = t
    k2 = k * k
    n = 1
    while t:
        t //= k2
        n += 2
        s += t // n
    return s >> 32


PI = 4 * (4 * atan_inv(5) - atan_inv(239))
LN2 = 2 * atanh_inv(3)                         # ln 2 = 2 atanh(1/3)
LN10 = 3 * LN2 + 2 * atanh_inv(9)              # ln 10 = 3 ln 2 + ln(5/4), ln(5/4) = 2 atanh(1/9)


def e_fixed():
    one = 1 << (P + 32)
    s, t, n = one, one, 1
    while t:
        t //= n
        s += t
        n += 1
    return s >> 32


E = e_fixed()
ONE = 1 << P


def div(a, b):
    return (a << P) // b


LOG2E = div(ONE, LN2)
LOG10E = div(ONE, LN10)
LOG10_2 = div(LN2, LN10)
LOG2_10 = div(LN10, LN2)


def ext128(v, scale=P):
    """value v * 2^-scale (v > 0) as (exponent field, significand, next 64 bits, sticky)"""
    n = v.bit_length()
    e2 = n - 1 - scale                         # unbiased exponent
    if n > 128:
        top = v >> (n - 128)
        rest = v & ((1 << (n - 128)) - 1)
    else:
        top = v << (128 - n)
        rest = 0
    hi, lo = top >> 64, top & ((1 << 64) - 1)
    if rest:
        lo |= 1                                # sticky: the value is not exactly hi.lo
    return e2 + 16383, hi, lo


def q128(v, scale=P, bits=113):
    """v * 2^-scale (v != 0) rounded to nearest-even with `bits` significant bits, as an IEEE quad (hi, lo)"""
    sign = 0
    if v < 0:
        sign, v = 1, -v
    n = v.bit_length()
    sh = n - bits
    if sh > 0:
        m = v >> sh
        r = v & ((1 << sh) - 1)
        half = 1 << (sh - 1)
        if r > half or (r == half and (m & 1)):
            m += 1
            if m.bit_length() > bits:
                m >>= 1
                sh += 1
    else:
        m = v << -sh
    e2 = (m.bit_length() - 1) + sh - scale
    m <<= 113 - bits                             # a shorter constant (ln2_hi) has trailing zero bits
    frac = m & ((1 << 112) - 1)
    hi = (sign << 63) | ((e2 + 16383) << 48) | (frac >> 64)
    lo = frac & ((1 << 64) - 1)
    return hi, lo


def q_exact(v, scale):
    return q128(v, scale)


out = []
w = out.append
w('/* SPDX-License-Identifier: MPL-2.0')
w(' *')
w(' * psmac_fpu_consts.h - generated by tools/mkfpuconsts.py (which says why and how): FMOVECR\'s')
w(' * constants to 128 bits, quadruple-precision constants for the elementary functions, and 2/pi')
w(' * for argument reduction. Do not edit; rerun the generator.')
w(' */')
w('#ifndef PSMAC_FPU_CONSTS_H')
w('#define PSMAC_FPU_CONSTS_H')
w('#include <stdint.h>')
w('')
w('/* FMOVECR: { offset, exponent field, significand, the 64 bits after it (lowest bit sticky) } */')
w('struct psmac_fpu_rom { uint8_t offset; uint16_t exp; uint64_t sig, extra; };')
w('static const struct psmac_fpu_rom psmac_fpu_rom[] = {')
rom = [(0x00, PI, 'pi'), (0x0b, LOG10_2, 'log10(2)'), (0x0c, E, 'e'), (0x0d, LOG2E, 'log2(e)'),
       (0x0e, LOG10E, 'log10(e)'), (0x30, LN2, 'ln(2)'), (0x31, LN10, 'ln(10)')]
rom.append((0x32, ONE, '1'))
for n in range(13):
    rom.append((0x33 + n, (10 ** (2 ** n)) << P, '10^%d' % (2 ** n)))
rom.sort()
for off, v, name in rom:
    e, hi, lo = ext128(v)
    w('    { 0x%02x, 0x%04x, UINT64_C(0x%016x), UINT64_C(0x%016x) },   /* %s */' % (off, e, hi, lo, name))
w('};')
w('')
w('/* quadruple-precision constants: { high 64 bits, low 64 bits } */')
consts = [
    ('PI', q128(PI)), ('PI_2', q128(PI // 2)), ('PI_4', q128(PI // 4)),
    ('LN2', q128(LN2)), ('LN2_HI', q128(LN2, bits=98)),
]
hi98 = q128(LN2, bits=98)
# ln2_lo = ln2 - ln2_hi: rebuild ln2_hi's exact value from its bits
def q_value(hi, lo):
    e2 = ((hi >> 48) & 0x7fff) - 16383
    m = (1 << 112) | ((hi & ((1 << 48) - 1)) << 64) | lo
    return m, e2 - 112                       # value = m * 2^(e2-112)
m, sh = q_value(*hi98)
ln2_hi_fixed = m << (P + sh) if P + sh >= 0 else m >> -(P + sh)
consts.append(('LN2_LO', q128(LN2 - ln2_hi_fixed)))
consts += [('LOG2E', q128(LOG2E)), ('LOG2_10', q128(LOG2_10)), ('LOG10E', q128(LOG10E)),
           ('LN10', q128(LN10))]
for name, (hi, lo) in consts:
    w('#define PSMAC_Q_%-8s { UINT64_C(0x%016x), UINT64_C(0x%016x) }' % (name, hi, lo))
w('')
NB = 16700
TWO_OVER_PI = (2 << (P + NB)) // PI           # 2/pi * 2^NB
words = (NB + 31) // 32
bits = TWO_OVER_PI >> (NB - 32 * words) if NB >= 32 * words else TWO_OVER_PI << (32 * words - NB)
w('/* 2/pi in binary: word k holds the bits of weight 2^-(32k+1) (its top bit) to 2^-(32k+32) */')
w('#define PSMAC_TWO_OVER_PI_BITS %d' % (32 * words))
w('static const uint32_t psmac_two_over_pi[%d] = {' % words)
vals = [(bits >> (32 * (words - 1 - k))) & 0xffffffff for k in range(words)]
for i in range(0, words, 8):
    w('    ' + ' '.join('0x%08x,' % x for x in vals[i:i + 8]))
w('};')
w('')
w('#endif')
sys.stdout.write('\n'.join(out) + '\n')
