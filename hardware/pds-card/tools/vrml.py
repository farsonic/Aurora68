"""vrml.py - box models for KiCad's 3D viewer, for the parts KiCad's library has no model of.

KiCad's VRML models are in tenths of an inch (2.54 mm per unit), x to the right, y up the board (away from the
viewer's front, so y = -board y), z up from the board's top face, in the footprint's own frame. On a footprint
placed on the bottom side KiCad turns the model over itself.

    write_plug(path)       the slot plug's body (DIN 41612 type C, 96 pins, male straight): 95.0 x 11.1 mm and
                           11.5 mm tall (Apple's Figure 17-4), symmetric about the footprint's origin
    write_pi3aplus(path)   a Raspberry Pi 3A+ turned components-down over its socket, in the socket footprint's
                           frame (origin on pin 1): its board 8.5 mm above the card, the parts that face the card
                           (USB, HDMI, audio, camera, display connectors, SoC, its own header) as boxes with Raspberry
                           Pi's drawing's sizes and heights, the microSD socket on its upper side. Not Raspberry Pi's
                           own STEP model, which is not redistributed here.
    write_fan(path)        the owner's 30 mm blower as a box (30 x 30 x 7 mm) with its outlet face marked, in the fan
                           footprint's frame (origin at the body's centre)
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import design as D

U = 2.54


def box(x0, y0, z0, x1, y1, z1, rgb):
    """A box between two corners given in board millimetres (y downwards), in KiCad's VRML frame."""
    cx, cy, cz = (x0 + x1) / 2 / U, -(y0 + y1) / 2 / U, (z0 + z1) / 2 / U
    sx, sy, sz = abs(x1 - x0) / U, abs(y1 - y0) / U, abs(z1 - z0) / U
    return ('Transform { translation %.4f %.4f %.4f children Shape { appearance Appearance { material Material { '
            'diffuseColor %.2f %.2f %.2f } } geometry Box { size %.4f %.4f %.4f } } }' % (cx, cy, cz, rgb[0], rgb[1], rgb[2], sx, sy, sz))


def write(path, boxes):
    with open(path, 'w') as f:
        f.write('#VRML V2.0 utf8\n# Generated by hardware/pds-card/tools/vrml.py (Aurora68 Card P). MPL-2.0.\n')
        for b in boxes:
            f.write(b + '\n')


def write_plug(path):
    write(path, [box(-5.55, -47.5, 0.0, 5.55, 47.5, 11.5, (0.85, 0.82, 0.75)),
                 box(-4.2, -45.0, 11.5, 4.2, 45.0, 11.9, (0.3, 0.3, 0.3))])


def write_pi3aplus(path):
    ox, oy = D.pi_header_pin(1)
    def uv(u0, v0, u1, v1, z0, z1, rgb):
        xa, ya = D.pi_xy(u0, v0)
        xb, yb = D.pi_xy(u1, v1)
        return box(xa - ox, ya - oy, z0, xb - ox, yb - oy, z1, rgb)
    g, top = D.PI_GAP, D.PI_TOP
    boxes = [uv(0, 0, D.PI_W, D.PI_D, g, top, (0.05, 0.45, 0.15))]                     # the board
    colours = {'USB-A': (0.75, 0.75, 0.78), 'HDMI': (0.75, 0.75, 0.78), 'audio': (0.15, 0.15, 0.15),
               'camera': (0.9, 0.9, 0.85), 'display': (0.9, 0.9, 0.85), 'header': (0.1, 0.1, 0.1),
               'micro-USB': (0.75, 0.75, 0.78), 'SoC + heatsink': (0.6, 0.6, 0.62)}
    for name, u0, u1, v0, v1, h in D.PI_TOP_PARTS:
        if name == 'SoC + heatsink':
            h = 1.2                                                                   # the SoC alone; a heatsink is optional
        if name == 'header':
            h = D.PI_HEADER_BODY                                                      # its plastic; the pins are in the socket
        boxes.append(uv(u0, v0, u1, v1, g - h, g, colours.get(name, (0.5, 0.5, 0.5))))
    for name, u0, u1, v0, v1, h in D.PI_UNDERSIDE:
        boxes.append(uv(u0, v0, u1, v1, top, top + h, (0.7, 0.7, 0.72)))
    write(path, boxes)


def write_fan(path):
    h = D.FAN_SIZE / 2
    cx, cy = D.FAN_AT
    ox, oy0, oy1 = D.fan_outlet()
    boxes = [box(-h, -h, 0.0, h, h, D.FAN_T, (0.12, 0.12, 0.13)),                                  # the body
             box(-9.0, -9.0, D.FAN_T, 9.0, 9.0, D.FAN_T + 0.05, (0.35, 0.35, 0.38)),               # the inlet
             box(h - 0.3, oy0 - cy + 0.5, 1.0, h + 0.05, oy1 - cy, D.FAN_T - 1.0, (0.85, 0.2, 0.15))]   # the outlet
    for (x, y) in D.fan_holes():
        boxes.append(box(x - cx - 1.6, y - cy - 1.6, D.FAN_T, x - cx + 1.6, y - cy + 1.6, D.FAN_T + 0.6, (0.7, 0.7, 0.72)))
    write(path, boxes)
